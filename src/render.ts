import { effectiveEpoch } from './config';
import type { AxisEntry, CellData, MatrixConfig } from './types';

export const FRAMEWORK_URL = 'https://github.com/wow-look-at-my/profiling-results-matrix';

export interface RenderMeta {
  /** Render timestamp (in-flight ages and the header line derive from it). */
  now: Date;
  /** What this write did, e.g. "`fib/O2` → done" or "re-render". */
  event: string;
  runId: string;
  runUrl: string;
  /** Browsable URL of the page's change history (footer link). */
  historyUrl: string;
}

/**
 * Pure renderer: config + recorded cells -> the results page markdown.
 * The page is derived state, recomputed in full from the cell data on every
 * write; it never has to merge and therefore can never conflict.
 */
export function renderPage(config: MatrixConfig, cells: ReadonlyMap<string, CellData>, meta: RenderMeta): string {
  const lines: string[] = [];
  lines.push(`# ${config.title}`);
  lines.push('');
  lines.push(
    `<sub>matrix \`${config.id}\` · epoch **${config.epoch}** · last update ${fmtUtc(meta.now)} · ` +
      `${meta.event} by [run ${meta.runId}](${meta.runUrl})</sub>`,
  );
  lines.push('');
  lines.push(`| | ${config.cols.map((c) => escapeCellText(c.label ?? c.key)).join(' | ')} |`);
  lines.push(`|---|${config.cols.map(() => '---').join('|')}|`);
  for (const row of config.rows) {
    const rendered = config.cols.map((col) =>
      renderCell(config, row, col, cells.get(`${row.key}/${col.key}`), meta.now),
    );
    lines.push(`| ${escapeCellText(row.label ?? row.key)} | ${rendered.join(' | ')} |`);
  }
  lines.push('');
  lines.push('### Legend');
  lines.push('');
  const unit = config.unit ? ` ${config.unit}` : '';
  lines.push('| Cell | Meaning |');
  lines.push('|---|---|');
  lines.push(`| **N${unit}** | measured value, linked to the run that produced it |`);
  lines.push('| *in flight* | a job has started measuring this cell and has not reported yet |');
  lines.push(
    `| *lost* | in flight for more than ${config.inFlightTtlMinutes} min (TTL) -- the job most ` +
      'likely died without cleanup |',
  );
  lines.push("| *aborted* | the job ended without reporting a result (recorded by the action's post step) |");
  lines.push('| *failed* | the job explicitly reported failure |');
  lines.push(
    '| ~~struck through~~ <sub>eN</sub> | stale: recorded against epoch N, older than the current ' +
      'effective epoch -- awaiting re-measurement |',
  );
  lines.push('| — | not measured yet |');
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push(
    `<sub>Auto-generated by [profiling-results-matrix](${FRAMEWORK_URL}) -- **do not edit by hand**. ` +
      `Cell data: \`data/${config.id}/*.json\` next to this page · ` +
      `[page history](${meta.historyUrl})</sub>`,
  );
  lines.push('');
  return lines.join('\n');
}

function renderCell(
  config: MatrixConfig,
  row: AxisEntry,
  col: AxisEntry,
  cell: CellData | undefined,
  now: Date,
): string {
  if (!cell) return '—';

  // Plain words, no emoji (user feedback): measured values are bold, every
  // non-value state is an italicized word -- distinguishable at a glance and
  // clean in GitHub-rendered tables.
  let body: string;
  const sub: string[] = [];
  switch (cell.status) {
    case 'done': {
      const unit = config.unit ? ` ${config.unit}` : '';
      body = `[**${escapeCellText(cell.value ?? '?')}${unit}**](${cell.runUrl})`;
      break;
    }
    case 'failed':
      body = `[*failed*](${cell.runUrl})`;
      break;
    case 'aborted':
      body = `[*aborted*](${cell.runUrl})`;
      break;
    case 'in-flight': {
      const ageMs = now.getTime() - Date.parse(cell.startedAt ?? cell.recordedAt);
      const lost = ageMs > config.inFlightTtlMinutes * 60_000;
      body = lost ? `[*lost*](${cell.runUrl})` : `[*in flight*](${cell.runUrl})`;
      sub.push(`started ${humanAge(ageMs)} ago`);
      break;
    }
    default:
      // Forward compatibility: an unknown status in a data file still renders.
      body = `[*${escapeCellText(String(cell.status))}*](${cell.runUrl})`;
  }

  // Staleness applies to reported results (done/failed): an older-epoch result
  // still renders, but struck through, until a new-epoch result replaces it.
  const stale =
    (cell.status === 'done' || cell.status === 'failed') && cell.epoch < effectiveEpoch(config, row, col);
  if (stale) {
    body = `~~${body}~~`;
    sub.unshift(`e${cell.epoch}`);
  }
  if (cell.note) sub.push(escapeCellText(cell.note));

  return sub.length > 0 ? `${body} <sub>${sub.join(' · ')}</sub>` : body;
}

/** "3m" / "2h" / "5d" -- coarse, monotonic with age, never negative. */
export function humanAge(ms: number): string {
  const minutes = Math.max(0, Math.floor(ms / 60_000));
  if (minutes < 60) return `${minutes}m`;
  const hours = Math.floor(minutes / 60);
  if (hours < 48) return `${hours}h`;
  return `${Math.floor(hours / 24)}d`;
}

/** "2026-07-09 18:42 UTC" */
export function fmtUtc(d: Date): string {
  return `${d.toISOString().slice(0, 16).replace('T', ' ')} UTC`;
}

/** Keep arbitrary text from breaking the GFM table: escape pipes, flatten newlines. */
export function escapeCellText(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}
